function atOffsetDays(daysFromNow: number, hourUtc: number, minuteUtc = 0): string {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + daysFromNow);
  d.setUTCHours(hourUtc, minuteUtc, 0, 0);
  return d.toISOString();
}

